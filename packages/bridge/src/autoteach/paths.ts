import { homedir } from "node:os";
import { join } from "node:path";

/**
 * Root for auto-teach session storage.
 *
 *   ~/browserops/autoteach-sessions/<session_id>/
 *     session.json      — AutoTeachSession metadata (mutable)
 *     trace.jsonl       — append-only AutoTeachTraceRecord per line
 *     runs.jsonl        — append-only AutoTeachRun per line
 *     drafts/v<N>.yaml  — distilled draft at version N
 *     final.yaml        — final saved procedure (also written to procedures store)
 *
 * Override via BROWSEROPS_AUTOTEACH_DIR for tests. Read at call time so
 * tests can mutate process.env in beforeEach.
 */
export function autoteachSessionsDir(): string {
  return (
    process.env["BROWSEROPS_AUTOTEACH_DIR"] ??
    join(homedir(), "browserops", "autoteach-sessions")
  );
}

export function sessionDir(sessionId: string): string {
  return join(autoteachSessionsDir(), safeId(sessionId));
}

export function sessionMetaPath(sessionId: string): string {
  return join(sessionDir(sessionId), "session.json");
}

export function tracePath(sessionId: string): string {
  return join(sessionDir(sessionId), "trace.jsonl");
}

export function runsPath(sessionId: string): string {
  return join(sessionDir(sessionId), "runs.jsonl");
}

export function draftsDir(sessionId: string): string {
  return join(sessionDir(sessionId), "drafts");
}

export function draftPath(sessionId: string, version: number): string {
  return join(draftsDir(sessionId), `v${version}.yaml`);
}

export function finalYamlPath(sessionId: string): string {
  return join(sessionDir(sessionId), "final.yaml");
}

/**
 * Defence-in-depth: session_id is generated by the bridge but we never
 * want a malformed value (e.g. from a resume call) to escape the
 * autoteach dir. Strip everything outside the alphabet our generator
 * uses (at_<base36>).
 */
export function safeId(sessionId: string): string {
  return sessionId.replace(/[^a-z0-9_-]/gi, "_");
}

/**
 * Generate a fresh session_id. Format: at_<base36-millis>_<base36-rand>.
 */
export function newSessionId(): string {
  const millis = Date.now().toString(36);
  const rand = Math.floor(Math.random() * 0xffffff).toString(36);
  return `at_${millis}_${rand}`;
}
