import { homedir } from "node:os";
import { join } from "node:path";

/**
 * Root for teach-mode session storage.
 *
 * Lives under ~/browserops/teach-sessions/ — same parent as procedures/ so
 * users have a single mental model: ~/browserops/ is the public memory area
 * where bridges read and write.
 *
 * Overridable via BROWSEROPS_TEACH_DIR for tests. Read at call time so tests
 * can mutate process.env in beforeEach.
 */
export function teachSessionsDir(): string {
  return (
    process.env["BROWSEROPS_TEACH_DIR"] ??
    join(homedir(), "browserops", "teach-sessions")
  );
}

export function eventsPath(sessionId: string): string {
  return join(teachSessionsDir(), `${safeId(sessionId)}.jsonl`);
}

export function metaPath(sessionId: string): string {
  return join(teachSessionsDir(), `${safeId(sessionId)}.meta.json`);
}

/**
 * Defence-in-depth: session_id is generated by the extension and we never
 * want a malformed value to escape the teach dir. Strip everything outside
 * the alphabet the extension uses (ts_<base36>).
 */
function safeId(sessionId: string): string {
  return sessionId.replace(/[^a-z0-9_-]/gi, "_");
}
